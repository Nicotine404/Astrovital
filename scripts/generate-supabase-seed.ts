/**
 * Writes supabase/seed.sql from the same seed builders the in-memory adapters use,
 * so a fresh Supabase project starts with identical demo data.
 *   npm run db:seed-sql
 */
import { writeFileSync } from "node:fs";
import { buildSeedTables } from "../src/features/health-monitoring/infrastructure/persistence/seed/telemetry.seed";
import { buildDiagnosticsSeed } from "../src/features/clinical-diagnostics/infrastructure/persistence/seed/diagnostics.seed";
import missionOps from "../src/features/mission-ops/infrastructure/persistence/seed/mission-ops.seed.json";

const now = new Date();
const telemetry = buildSeedTables(now);
const diagnostics = buildDiagnosticsSeed(now);

type Rows = Record<string, unknown>[];

// Insertion order respects foreign keys.
const tables: [string, Rows][] = [
  ["astronauts", telemetry.astronauts.map((r, i) => ({ ...r, created_at: new Date(now.getTime() + i * 1000).toISOString() }))],
  ["vital_signs", telemetry.vital_signs as unknown as Rows],
  ["organ_assessments", telemetry.organ_assessments as unknown as Rows],
  ["radiation_dosimetry", telemetry.radiation_dosimetry as unknown as Rows],
  ["radiation_readings", telemetry.radiation_readings as unknown as Rows],
  ["musculoskeletal_status", telemetry.musculoskeletal_status as unknown as Rows],
  ["musculoskeletal_history", telemetry.musculoskeletal_history as unknown as Rows],
  ["mental_checkins", telemetry.mental_checkins as unknown as Rows],
  ["nutrition_logs", telemetry.nutrition_logs as unknown as Rows],
  ["diagnoses", diagnostics.diagnoses as unknown as Rows],
  ["clinical_files", diagnostics.clinical_files as unknown as Rows],
  ["medkit_items", missionOps.medkit_items],
  ["eclss_readings", missionOps.eclss_readings.map((r, i) => ({ ...r, sort_order: i }))],
];

const tag = "$seed$";
const out: string[] = [
  "-- Generated by scripts/generate-supabase-seed.ts. Do not edit by hand.",
  `-- Mission clock at generation: ${now.toISOString()}`,
  "begin;",
  `update mission_state set gravity_environment = '${telemetry.mission_state[0]?.gravity_environment ?? "MARTIAN"}', habitat = '${telemetry.mission_state[0]?.habitat ?? "MARS_BASE"}' where id = 1;`,
];

for (const [table, rows] of tables) {
  if (!rows.length) continue;
  const cols = Object.keys(rows[0]).join(", ");
  const json = JSON.stringify(rows);
  if (json.includes(tag)) throw new Error(`Seed data for ${table} contains the dollar-quote tag`);
  out.push(`insert into ${table} (${cols})`, `select ${cols} from jsonb_populate_recordset(null::${table}, ${tag}${json}${tag}::jsonb);`);
}
out.push("commit;", "");

writeFileSync("supabase/seed.sql", out.join("\n"));
console.log(`supabase/seed.sql: ${tables.reduce((n, [, r]) => n + r.length, 0)} rows`);
